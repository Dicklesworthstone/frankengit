//! Complete target-only artifacts without enumerating the target's history.
//!
//! Every omitted object is behind a native edge independently read from the
//! selected target tree. Only changed directory pairs are expanded. Objects
//! reused solely from older target history may be sent redundantly; that is a
//! bounded transport cost, never permission to omit an unproved dependency.

use std::collections::{BTreeMap, BTreeSet};
use std::sync::Arc;

use fgit_admission::ProjectionFailure;
use fgit_admission::merge::native::objects::{
    FrontierObjectHeaders, MergeObjectLimits, ObjectFrontier, validate_commit_closure_above,
};
use fgit_git_object::{AcceptanceProfile, ObjectError, ObjectType, ParseLimits, ParsedObject};
use fgit_pack::{CanonicalObjectSource, Deadline, PackError, PackWriteError, verify_native_object};
use fgit_types::{GitOid, RefusalCode};

struct TreeEntry {
    kind: ObjectType,
    id: GitOid,
}

// No Clone implementation: cached directory payloads are shared, not copied.
// The directory index avoids scanning every regular-file entry on each pair.
struct Tree {
    entries: BTreeMap<Vec<u8>, TreeEntry>,
    directories: BTreeMap<Vec<u8>, GitOid>,
}

/// Verify the entire single-parent candidate chain to `target`, then collect
/// every dependency not proved reachable from its current tree. `target` must
/// already be independently selected by the caller. The source still enforces
/// original-object authorization and native-header availability.
/// Frontier discovery and candidate validation each retain the existing native
/// validation ceilings. The node's source-read byte budget is shared across
/// both phases, planning and packing; generated bytes retain the planner bound.
pub(super) fn objects_above_target(
    source: &(impl CanonicalObjectSource + FrontierObjectHeaders),
    target: GitOid,
    candidate: GitOid,
    max_commits: usize,
    limits: MergeObjectLimits,
    deadline: &mut impl Deadline,
) -> Result<BTreeSet<GitOid>, ProjectionFailure> {
    let maximum = MergeObjectLimits::default();
    if max_commits == 0
        || limits.max_objects == 0
        || limits.max_objects > maximum.max_objects
        || limits.max_edges == 0
        || limits.max_edges > maximum.max_edges
        || limits.max_object_bytes == 0
        || limits.max_object_bytes > maximum.max_object_bytes
        || limits.max_total_bytes == 0
        || limits.max_total_bytes > maximum.max_total_bytes
    {
        return Err(budget());
    }
    if target.is_zero() || candidate.is_zero() || target.algorithm() != candidate.algorithm() {
        return Err(invalid());
    }
    let mut walk = Walk {
        source,
        limits,
        deadline,
        objects: 0,
        bytes: 0,
        edges: 0,
        trees: BTreeMap::new(),
        expanded: BTreeSet::new(),
        frontier: BTreeMap::new(),
    };
    let (target_tree, _) = walk.commit(target, false)?;
    walk.remember(target, ObjectType::Commit)?;
    walk.remember(target_tree, ObjectType::Tree)?;
    let mut current = candidate;
    let mut commits = BTreeSet::new();
    let mut candidate_trees = BTreeSet::new();
    while current != target {
        walk.checkpoint()?;
        if commits.len() >= max_commits {
            return Err(budget());
        }
        if !commits.insert(current) {
            return Err(invalid());
        }
        let (tree, parents) = walk.commit(current, true)?;
        let [parent] = parents.as_slice() else {
            return Err(invalid());
        };
        candidate_trees.insert(tree);
        current = *parent;
    }
    // Nothing is required for an all-dropped rebase that ends at onto itself.
    if candidate == target {
        walk.checkpoint()?;
        return Ok(BTreeSet::new());
    }
    let mut pending: BTreeSet<_> = candidate_trees
        .into_iter()
        .map(|tree| (tree, target_tree))
        .collect();
    let mut paired = BTreeSet::new();
    while let Some((new, old)) = pending.pop_first() {
        walk.checkpoint()?;
        if new == old || !paired.insert((new, old)) {
            continue;
        }
        if paired.len() > limits.max_objects {
            return Err(budget());
        }
        let old_entries = walk.prove_tree(old)?;
        let new_entries = walk.tree(new)?;
        for (name, child) in &new_entries.directories {
            walk.checkpoint()?;
            // A cached tree can be paired with several inherited directories.
            // Charge each comparison, but never rescan its regular-file leaves.
            walk.charge_edges(1)?;
            if walk.frontier.contains_key(child) {
                continue;
            }
            if let Some(before) = old_entries.directories.get(name) {
                if pending.len() >= limits.max_edges {
                    return Err(budget());
                }
                pending.insert((*child, *before));
            }
        }
    }
    walk.checkpoint()?;
    let frontier: BTreeSet<_> = std::mem::take(&mut walk.frontier).into_keys().collect();
    // Discovery and independent validation have different ownership. Do not
    // retain the parsed directory inventory while the validator reads payloads.
    walk.trees.clear();
    walk.expanded.clear();
    walk.checkpoint()?;
    // This validator independently hashes all new/borrowed bytes and checks
    // every reused edge's actual native kind. No target-history membership
    // claim is taken from a planner's object list or the repository-wide set.
    let result = validate_commit_closure_above(
        source,
        candidate,
        ObjectFrontier::with_headers(&frontier, source),
        limits,
        walk.deadline,
    )?;
    Ok(result.objects)
}

struct Walk<'a, S, D> {
    source: &'a S,
    limits: MergeObjectLimits,
    deadline: &'a mut D,
    objects: usize,
    bytes: usize,
    edges: usize,
    trees: BTreeMap<GitOid, Arc<Tree>>,
    // A verified cached candidate tree is not proof of target reachability.
    expanded: BTreeSet<GitOid>,
    frontier: BTreeMap<GitOid, ObjectType>,
}

impl<S: CanonicalObjectSource, D: Deadline> Walk<'_, S, D> {
    fn checkpoint(&mut self) -> Result<(), ProjectionFailure> {
        if self.deadline.checkpoint() {
            Ok(())
        } else {
            Err(ProjectionFailure::Unavailable(
                RefusalCode::CancellationInProgress,
            ))
        }
    }

    fn read(
        &mut self,
        id: GitOid,
        kind: ObjectType,
        strict: bool,
    ) -> Result<ParsedObject, ProjectionFailure> {
        self.checkpoint()?;
        if self.objects >= self.limits.max_objects {
            return Err(budget());
        }
        let object = self.source.load(&id).map_err(source_failure)?;
        self.checkpoint()?;
        if object.id() != id || object.object_type() != kind {
            return Err(invalid());
        }
        self.objects += 1;
        self.bytes = self
            .bytes
            .checked_add(object.body().len())
            .filter(|bytes| *bytes <= self.limits.max_total_bytes)
            .ok_or_else(budget)?;
        verify_native_object(
            id.algorithm(),
            kind,
            object.body(),
            &id,
            if strict {
                AcceptanceProfile::StrictCreate
            } else {
                AcceptanceProfile::GitCompatibleImport
            },
            &ParseLimits {
                max_object_bytes: self.limits.max_object_bytes,
                max_tree_entries: self.limits.max_edges,
                tree_reference_bytes: id.algorithm().digest_len(),
                ..ParseLimits::default()
            },
        )
        .map_err(parse_failure)
    }

    fn charge_edges(&mut self, count: usize) -> Result<(), ProjectionFailure> {
        self.edges = self
            .edges
            .checked_add(count)
            .filter(|edges| *edges <= self.limits.max_edges)
            .ok_or_else(budget)?;
        Ok(())
    }

    fn commit(
        &mut self,
        id: GitOid,
        strict: bool,
    ) -> Result<(GitOid, Vec<GitOid>), ProjectionFailure> {
        let ParsedObject::Commit(commit) = self.read(id, ObjectType::Commit, strict)? else {
            return Err(invalid());
        };
        if commit
            .headers()
            .iter()
            .filter(|h| h.name == b"tree")
            .count()
            != 1
            || commit
                .headers()
                .iter()
                .any(|h| (h.name == b"tree" || h.name == b"parent") && !h.continuations.is_empty())
        {
            return Err(invalid());
        }
        let parse = |bytes: &[u8]| {
            let value = std::str::from_utf8(bytes).map_err(|_| invalid())?;
            GitOid::from_hex(id.algorithm(), &value.to_ascii_lowercase()).map_err(|_| invalid())
        };
        let tree = parse(commit.tree_reference().ok_or_else(invalid)?)?;
        let mut parents = Vec::new();
        for parent in commit.parent_references() {
            self.checkpoint()?;
            self.charge_edges(1)?;
            parents.try_reserve(1).map_err(|_| budget())?;
            parents.push(parse(parent)?);
        }
        self.charge_edges(1)?;
        Ok((tree, parents))
    }

    fn tree(&mut self, id: GitOid) -> Result<Arc<Tree>, ProjectionFailure> {
        self.checkpoint()?;
        if let Some(tree) = self.trees.get(&id) {
            return Ok(Arc::clone(tree));
        }
        let ParsedObject::Tree(entries) = self.read(id, ObjectType::Tree, false)? else {
            return Err(invalid());
        };
        // Charge every native entry, including gitlinks, before constructing
        // either index. This pays for parsing and at most one proof expansion;
        // repeated directory-pair comparisons are charged separately above.
        self.charge_edges(entries.len())?;
        let mut tree = BTreeMap::new();
        let mut directories = BTreeMap::new();
        for entry in entries {
            self.checkpoint()?;
            let mode = std::str::from_utf8(&entry.mode)
                .ok()
                .and_then(|mode| u32::from_str_radix(mode, 8).ok())
                .ok_or_else(invalid)?;
            let kind = match mode & 0o170_000 {
                0o040_000 => ObjectType::Tree,
                0o100_000 | 0o120_000 => ObjectType::Blob,
                0o160_000 => continue,
                _ => return Err(invalid()),
            };
            let hex: String = entry
                .object_id
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect();
            let child = GitOid::from_hex(id.algorithm(), &hex).map_err(|_| invalid())?;
            if kind == ObjectType::Tree {
                directories.insert(entry.name.clone(), child);
            }
            if child.is_zero()
                || tree
                    .insert(entry.name, TreeEntry { kind, id: child })
                    .is_some()
            {
                return Err(invalid());
            }
        }
        let tree = Arc::new(Tree {
            entries: tree,
            directories,
        });
        self.trees.insert(id, Arc::clone(&tree));
        Ok(tree)
    }

    // Only a tree reached from a selected target edge may extend the omitted
    // object frontier. Parsing/caching a source-only tree never grants this.
    fn prove_tree(&mut self, id: GitOid) -> Result<Arc<Tree>, ProjectionFailure> {
        self.checkpoint()?;
        if self.frontier.get(&id) != Some(&ObjectType::Tree) {
            return Err(invalid());
        }
        let tree = self.tree(id)?;
        if self.expanded.insert(id) {
            for entry in tree.entries.values() {
                self.checkpoint()?;
                self.remember(entry.id, entry.kind)?;
            }
        }
        Ok(tree)
    }

    fn remember(&mut self, id: GitOid, kind: ObjectType) -> Result<(), ProjectionFailure> {
        if id.is_zero() {
            return Err(invalid());
        }
        if self.frontier.len() >= self.limits.max_edges && !self.frontier.contains_key(&id) {
            return Err(budget());
        }
        if self
            .frontier
            .insert(id, kind)
            .is_some_and(|expected| expected != kind)
        {
            return Err(invalid());
        }
        Ok(())
    }
}

const fn invalid() -> ProjectionFailure {
    ProjectionFailure::Refuse(RefusalCode::EvidenceInvalid)
}
const fn budget() -> ProjectionFailure {
    ProjectionFailure::Unavailable(RefusalCode::ResourceBudgetExceeded)
}
const fn parse_failure(error: PackError) -> ProjectionFailure {
    match error {
        PackError::ObjectParse(
            ObjectError::ObjectTooLarge { .. }
            | ObjectError::TooManyTreeEntries { .. }
            | ObjectError::HeaderLimitExceeded { .. }
            | ObjectError::AllocationFailure,
        ) => budget(),
        _ => invalid(),
    }
}
const fn source_failure(error: PackWriteError) -> ProjectionFailure {
    match error {
        PackWriteError::Pack(PackError::DeadlineExceeded) => {
            ProjectionFailure::Unavailable(RefusalCode::CancellationInProgress)
        }
        _ => ProjectionFailure::Unavailable(RefusalCode::EvidenceMissing),
    }
}

