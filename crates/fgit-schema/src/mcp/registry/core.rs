/// Looks up an entry in the registry by name.
#[must_use]
pub fn find_tool(name: &str) -> Option<&'static McpToolEntry> {
    REGISTRY.iter().find(|tool| tool.name == name)
}

/// Looks up an entry in the registry by name and exact version.
#[must_use]
pub fn find_tool_version(name: &str, version: u32) -> Option<&'static McpToolEntry> {
    REGISTRY
        .iter()
        .find(|tool| tool.name == name && tool.version == version)
}

