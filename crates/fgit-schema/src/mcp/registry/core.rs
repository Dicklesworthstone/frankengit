    fn exact_tool_count_and_ordering() {
        assert_eq!(REGISTRY.len(), 47);
        for pair in REGISTRY.windows(2) {
            assert!(
                (pair[0].name, pair[0].version) < (pair[1].name, pair[1].version),
                "Ordering violation: {} must precede {}",
                pair[0].name,
                pair[1].name
            );
        }
    }
