//! Canonical, typed evidence bodies for one admitted decision.
//!
//! These bodies are deliberately derived from the exact admission context,
//! authenticated basis, request, and evaluated normal form.  Callers cannot
//! supply a bare root: the node stages these bodies under their recomputed
//! content identities before an RCR can quote them.

use fgit_chronicle::PublicationBasis;
use fgit_codec::{CanonicalBody, CodecRefusal, CryptoBodyIdentity, Decoder, Encoder, body_id};
use fgit_txn::{
    TransactionFoldReport, canonical_fold_bytes, canonical_forge_effect_bytes,
    canonical_outbox_effect_bytes, canonical_retention_effect_bytes,
};
use fgit_types::{
    Digest, DomainTag, PolicyEpoch, PrincipalId, PrincipalSnapshotId, RefusalCode,
    RepositoryAuthorityHeadId, RepositoryId, SchemaFamily, TenantId, TxId,
};

use crate::AdmissionContext;

/// Stable refusal-record detail for a refusal supported by
/// [`RefusalEvidence`].
///
/// The terminal code and policy epoch are separate typed fields of the
/// refusal record; this text only identifies the durable evidence mechanism
/// and therefore cannot vary by caller input.
pub const DURABLE_REFUSAL_EVIDENCE_DETAIL: &str = "durable canonical refusal evidence";

/// Immutable principal identity and configuration basis for one admission decision.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PrincipalSnapshot {
    tenant_id: TenantId,
    repository_id: RepositoryId,
    principal_id: PrincipalId,
    configuration_root: Digest,
}

impl PrincipalSnapshot {
    const fn from_context(context: &AdmissionContext, basis: &PublicationBasis) -> Self {
        Self {
            tenant_id: context.tenant_id,
            repository_id: context.repository_id,
            principal_id: context.principal_id,
            configuration_root: basis.body().configuration_root,
        }
    }

    /// Repository that scopes this immutable snapshot.
    #[must_use]
    pub const fn repository_id(&self) -> RepositoryId {
        self.repository_id
    }
}

impl CanonicalBody for PrincipalSnapshot {
    const DOMAIN: DomainTag = DomainTag::from_static("frankengit/principal-snapshot/v1");
    const SCHEMA_FAMILY: SchemaFamily = SchemaFamily::from_static("principal-snapshot");
    const SCHEMA_MAJOR: u16 = 1;
    const SCHEMA_MINOR: u16 = 0;

    fn write_payload(&self, out: &mut Encoder) -> Result<(), CodecRefusal> {
        out.write_opaque_id(self.tenant_id.as_bytes());
        out.write_opaque_id(self.repository_id.as_bytes());
        out.write_opaque_id(self.principal_id.as_bytes());
        out.write_digest(&self.configuration_root)
    }

    fn read_payload(input: &mut Decoder<'_>) -> Result<Self, CodecRefusal> {
        Ok(Self {
            tenant_id: TenantId::from_bytes(input.read_opaque_id("principal_snapshot.tenant")?),
            repository_id: RepositoryId::from_bytes(
                input.read_opaque_id("principal_snapshot.repository")?,
            ),
            principal_id: PrincipalId::from_bytes(
                input.read_opaque_id("principal_snapshot.principal")?,
            ),
            configuration_root: input.read_digest()?,
        })
    }
}

/// Policy decision evidence bound to the exact request and authority basis.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PolicyDecisionEvidence {
    tx_id: TxId,
    request_digest: Digest,
    principal_snapshot_id: PrincipalSnapshotId,
    policy_epoch: PolicyEpoch,
}

impl CanonicalBody for PolicyDecisionEvidence {
    const DOMAIN: DomainTag = DomainTag::from_static("frankengit/admission-policy-decision/v1");
    const SCHEMA_FAMILY: SchemaFamily = SchemaFamily::from_static("admission-policy-decision");
    const SCHEMA_MAJOR: u16 = 1;
    const SCHEMA_MINOR: u16 = 0;

    fn write_payload(&self, out: &mut Encoder) -> Result<(), CodecRefusal> {
        out.write_internal_object_id(self.tx_id.as_internal_object_id())?;
        out.write_digest(&self.request_digest)?;
        out.write_internal_object_id(self.principal_snapshot_id.as_internal_object_id())?;
        out.write_scalar(self.policy_epoch.get());
        Ok(())
    }

    fn read_payload(input: &mut Decoder<'_>) -> Result<Self, CodecRefusal> {
        Ok(Self {
            tx_id: TxId::from_internal_object_id(input.read_internal_object_id()?)
                .map_err(CodecRefusal::from)?,
            request_digest: input.read_digest()?,
            principal_snapshot_id: PrincipalSnapshotId::from_internal_object_id(
                input.read_internal_object_id()?,
            )
            .map_err(CodecRefusal::from)?,
            policy_epoch: PolicyEpoch::try_new(input.read_scalar("policy_epoch")?)
                .map_err(CodecRefusal::from)?,
        })
    }
}

