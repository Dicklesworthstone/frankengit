/// Immutable evidence for one terminal refusal at one exact authority basis.
///
/// This is intentionally not a [`fgit_codec::RefusalRecordBody`]. The refusal
/// record quotes this body's root, so using the record itself here would make
/// the commitment circular. The snapshot identity binds the authenticated
/// principal and configuration, while the head identity binds the exact
/// authority basis on which the policy code was evaluated.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RefusalEvidence {
    principal_snapshot_id: PrincipalSnapshotId,
    basis_head_id: RepositoryAuthorityHeadId,
    tx_id: TxId,
    policy_epoch: PolicyEpoch,
    code: RefusalCode,
}

impl CanonicalBody for RefusalEvidence {
    const DOMAIN: DomainTag = DomainTag::from_static("frankengit/admission-refusal-evidence/v1");
    const SCHEMA_FAMILY: SchemaFamily = SchemaFamily::from_static("admission-refusal-evidence");
    const SCHEMA_MAJOR: u16 = 1;
    const SCHEMA_MINOR: u16 = 0;

    fn write_payload(&self, out: &mut Encoder) -> Result<(), CodecRefusal> {
        out.write_internal_object_id(self.principal_snapshot_id.as_internal_object_id())?;
        out.write_internal_object_id(self.basis_head_id.as_internal_object_id())?;
        out.write_internal_object_id(self.tx_id.as_internal_object_id())?;
        out.write_scalar(self.policy_epoch.get());
        out.write_scalar(self.code.code_point());
        Ok(())
    }

    fn read_payload(input: &mut Decoder<'_>) -> Result<Self, CodecRefusal> {
        Ok(Self {
            principal_snapshot_id: PrincipalSnapshotId::from_internal_object_id(
                input.read_internal_object_id()?,
            )
            .map_err(CodecRefusal::from)?,
            basis_head_id: RepositoryAuthorityHeadId::from_internal_object_id(
                input.read_internal_object_id()?,
            )
            .map_err(CodecRefusal::from)?,
            tx_id: TxId::from_internal_object_id(input.read_internal_object_id()?)
                .map_err(CodecRefusal::from)?,
            policy_epoch: PolicyEpoch::try_new(input.read_scalar("policy_epoch")?)
                .map_err(CodecRefusal::from)?,
            code: RefusalCode::from_code_point(input.read_scalar("refusal_code")?)
                .map_err(CodecRefusal::from)?,
        })
    }
}

/// Immutable bodies needed to materialize one durable terminal refusal.
///
/// The principal snapshot is staged beside its referring refusal-evidence
/// body. This keeps the refusal root derivable from typed bytes while also
/// leaving an independently identifiable configuration/principal witness.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RefusalEvidenceBodies {
    principal_snapshot: PrincipalSnapshot,
    refusal_evidence: RefusalEvidence,
}

impl RefusalEvidenceBodies {
    /// Derives the complete refusal witness from the authenticated context,
    /// exact basis, terminal transaction identity, and evaluated refusal.
    pub fn derive(
        context: &AdmissionContext,
        basis: &PublicationBasis,
        tx_id: TxId,
        code: RefusalCode,
    ) -> Result<Self, RefusalCode> {
        let principal_snapshot = PrincipalSnapshot::from_context(context, basis);
        let principal_snapshot_id = principal_snapshot_id(&principal_snapshot)?;
        Ok(Self {
            refusal_evidence: RefusalEvidence {
                principal_snapshot_id,
                basis_head_id: basis.id(),
                tx_id,
                policy_epoch: basis.body().policy_epoch,
                code,
            },
            principal_snapshot,
        })
    }

    #[must_use]
    pub const fn principal_snapshot(&self) -> &PrincipalSnapshot {
        &self.principal_snapshot
    }

    #[must_use]
    pub const fn refusal_evidence(&self) -> &RefusalEvidence {
        &self.refusal_evidence
    }
}

/// All immutable evidence bodies required for one committing decision.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DecisionEvidenceBodies {
    principal_snapshot: PrincipalSnapshot,
    policy_decision: PolicyDecisionEvidence,
    invariant_evidence: InvariantEvidence,
    forge_event_batch: ForgeEventBatch,
    outbox_effect_batch: OutboxEffectBatch,
    retention_delta: RetentionDelta,
}

impl DecisionEvidenceBodies {
    /// Derives every body from the exact typed admission inputs.
    pub fn derive(
        context: &AdmissionContext,
        basis: &PublicationBasis,
        request: &fgit_reference::intent::TransactionRequest,
        fold: &TransactionFoldReport,
    ) -> Result<Self, RefusalCode> {
        let effects = fold
            .effects()
            .ok_or(RefusalCode::ConflictingSemanticEffects)?;
        let principal_snapshot = PrincipalSnapshot::from_context(context, basis);
        let principal_snapshot_id = principal_snapshot_id(&principal_snapshot)?;
        Ok(Self {
            policy_decision: PolicyDecisionEvidence {
                tx_id: request.tx_id,
                request_digest: request.canonical_request_digest,
                principal_snapshot_id,
                policy_epoch: basis.body().policy_epoch,
            },
            invariant_evidence: InvariantEvidence {
                fold_bytes: canonical_fold_bytes(request, fold)
                    .map_err(|_| RefusalCode::CanonicalFramingInvalid)?,
            },
            forge_event_batch: ForgeEventBatch {
                effect_bytes: canonical_forge_effect_bytes(effects)
                    .map_err(|_| RefusalCode::CanonicalFramingInvalid)?,
            },
            outbox_effect_batch: OutboxEffectBatch {
                effect_bytes: canonical_outbox_effect_bytes(effects)
                    .map_err(|_| RefusalCode::CanonicalFramingInvalid)?,
            },
            retention_delta: RetentionDelta {
                effect_bytes: canonical_retention_effect_bytes(effects)
                    .map_err(|_| RefusalCode::CanonicalFramingInvalid)?,
            },
            principal_snapshot,
        })
    }

    /// Reassembles bodies after the durable store decoded and authenticated
    /// each separate body frame.  There is intentionally no constructor from
    /// roots: every root used by admission must first be recomputed from one
    /// of these concrete canonical bodies.
    #[must_use]
    pub const fn from_decoded(
        principal_snapshot: PrincipalSnapshot,
        policy_decision: PolicyDecisionEvidence,
        invariant_evidence: InvariantEvidence,
        forge_event_batch: ForgeEventBatch,
        outbox_effect_batch: OutboxEffectBatch,
        retention_delta: RetentionDelta,
    ) -> Self {
        Self {
            principal_snapshot,
            policy_decision,
            invariant_evidence,
            forge_event_batch,
            outbox_effect_batch,
            retention_delta,
        }
    }

    #[must_use]
    pub const fn principal_snapshot(&self) -> &PrincipalSnapshot {
        &self.principal_snapshot
    }
    #[must_use]
    pub const fn policy_decision(&self) -> &PolicyDecisionEvidence {
        &self.policy_decision
    }
    #[must_use]
    pub const fn invariant_evidence(&self) -> &InvariantEvidence {
        &self.invariant_evidence
    }
    #[must_use]
    pub const fn forge_event_batch(&self) -> &ForgeEventBatch {
        &self.forge_event_batch
    }
    #[must_use]
    pub const fn outbox_effect_batch(&self) -> &OutboxEffectBatch {
        &self.outbox_effect_batch
    }
    #[must_use]
    pub const fn retention_delta(&self) -> &RetentionDelta {
        &self.retention_delta
    }
}

/// Domain-pinned identity of a principal snapshot body.
pub fn principal_snapshot_id(body: &PrincipalSnapshot) -> Result<PrincipalSnapshotId, RefusalCode> {
    body_id(&CryptoBodyIdentity, body)
        .map_err(|_| RefusalCode::CanonicalFramingInvalid)
        .and_then(|identity| {
            PrincipalSnapshotId::from_internal_object_id(identity)
                .map_err(|_| RefusalCode::CanonicalFramingInvalid)
        })
}

/// Domain-pinned root of any immutable evidence body.
pub fn evidence_root<Body: CanonicalBody>(body: &Body) -> Result<Digest, RefusalCode> {
    let identity =
        body_id(&CryptoBodyIdentity, body).map_err(|_| RefusalCode::CanonicalFramingInvalid)?;
    Ok(Digest::new(identity.algorithm(), *identity.digest()))
}

#[cfg(test)]
mod tests {
    use fgit_authority::HeadKey;
    use fgit_chronicle::PublicationBasis;
    use fgit_codec::harness::{digest_of, head_id, tx_id};
    use fgit_codec::{RepositoryAuthorityHeadBody, decode_body, encode_body};
    use fgit_reference::effect::{FoldOutcome, FoldReport, NetEffects};
    use fgit_reference::intent::{DurabilityProfile, IdempotencyKey, TransactionRequest};
    use fgit_types::{
        GitHashAlgorithm, HeadGeneration, PolicyEpoch, PrincipalId, RegistryEpoch, SchemaFamily,
        SchemaId,
    };

    use super::*;

    fn fixture() -> (
        AdmissionContext,
        PublicationBasis,
        TransactionRequest,
        TransactionFoldReport,
    ) {
        let tenant_id = TenantId::from_bytes([0x11; 16]);
        let repository_id = RepositoryId::from_bytes([0x22; 16]);
        let principal_id = PrincipalId::from_bytes([0x33; 16]);
        let context = AdmissionContext {
            head_key: HeadKey::new(b"evidence-fixture-head".to_vec())
                .expect("fixed bounded head key"),
            tenant_id,
            repository_id,
            principal_id,
            idempotency_key: fgit_authority::IdempotencyKey::new(b"evidence-session".to_vec())
                .expect("fixed bounded authority idempotency key"),
            object_format: GitHashAlgorithm::Sha1,
        };
        let basis = PublicationBasis::new(
            head_id(),
            RepositoryAuthorityHeadBody {
                repository_id,
                generation: HeadGeneration::FIRST,
                predecessor_head_id: None,
                decision_tail_id: None,
                latest_decision_sequence: None,
                latest_committed_rcr_id: None,
                latest_repository_sequence: None,
                ref_root: digest_of(1),
                forge_position_root: digest_of(2),
                outcome_index_root: digest_of(3),
                retention_root: digest_of(4),
                outbox_root: digest_of(5),
                configuration_root: digest_of(6),
                policy_epoch: PolicyEpoch::FIRST,
                format_registry_epoch: RegistryEpoch::FIRST,
                last_checkpoint_id: None,
            },
        );
        let request = TransactionRequest {
            tx_id: tx_id(),
            tenant: tenant_id,
            repository: repository_id,
            principal: principal_id,
            schema: SchemaId::new(SchemaFamily::from_static("evidence-fixture"), 1, 0),
            idempotency_key: IdempotencyKey::new(
                fgit_types::AsciiSlug::try_new("test", b"evidence-request")
                    .expect("fixed idempotency label"),
            ),
            canonical_request_digest: digest_of(7),
            statements: Vec::new(),
            promised_closure: std::collections::BTreeSet::default(),
            atomic: true,
            durability: DurabilityProfile::CanonicalSource,
        };
        let fold = FoldReport {
            outcome: FoldOutcome::Folded(NetEffects::default()),
            mappings: Vec::new(),
        };
        (context, basis, request, fold)
    }

    #[test]
    fn decision_bodies_are_canonical_round_trips_with_distinct_roots() {
        let (context, basis, request, fold) = fixture();
        let first = DecisionEvidenceBodies::derive(&context, &basis, &request, &fold)
            .expect("empty folded decision has complete evidence bodies");
        let second = DecisionEvidenceBodies::derive(&context, &basis, &request, &fold)
            .expect("derivation is deterministic");
        assert_eq!(first, second, "same decision derives identical body values");

        let snapshot_frame = encode_body(first.principal_snapshot()).expect("snapshot frames");
        let policy_frame = encode_body(first.policy_decision()).expect("policy frames");
        let invariant_frame = encode_body(first.invariant_evidence()).expect("invariant frames");
        let forge_frame = encode_body(first.forge_event_batch()).expect("forge frames");
        let outbox_frame = encode_body(first.outbox_effect_batch()).expect("outbox frames");
        let retention_frame = encode_body(first.retention_delta()).expect("retention frames");

        assert_eq!(
            decode_body::<PrincipalSnapshot>(&snapshot_frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("snapshot frame decodes"),
            first.principal_snapshot().clone()
        );
        assert_eq!(
            decode_body::<PolicyDecisionEvidence>(&policy_frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("policy frame decodes"),
            first.policy_decision().clone()
        );
        assert_eq!(
            decode_body::<InvariantEvidence>(&invariant_frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("invariant frame decodes"),
            first.invariant_evidence().clone()
        );
        assert_eq!(
            decode_body::<ForgeEventBatch>(&forge_frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("forge frame decodes"),
            first.forge_event_batch().clone()
        );
        assert_eq!(
            decode_body::<OutboxEffectBatch>(&outbox_frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("outbox frame decodes"),
            first.outbox_effect_batch().clone()
        );
        assert_eq!(
            decode_body::<RetentionDelta>(&retention_frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("retention frame decodes"),
            first.retention_delta().clone()
        );

        let forge_root = evidence_root(first.forge_event_batch()).expect("forge root derives");
        let outbox_root = evidence_root(first.outbox_effect_batch()).expect("outbox root derives");
        let retention_root =
            evidence_root(first.retention_delta()).expect("retention root derives");
        assert_ne!(
            forge_root, outbox_root,
            "forge and outbox domains are separate"
        );
        assert_ne!(
            forge_root, retention_root,
            "forge and retention domains are separate"
        );
        assert_ne!(
            outbox_root, retention_root,
            "outbox and retention domains are separate"
        );
    }

    #[test]
    fn aborted_fold_never_mints_commit_evidence_bodies() {
        let (context, basis, request, mut fold) = fixture();
        fold.outcome = FoldOutcome::Aborted {
            code: RefusalCode::ExpectedOldRefMismatch,
            at: fgit_reference::intent::IntentAddress {
                statement: fgit_reference::intent::StatementIndex(0),
                intent: fgit_reference::intent::IntentIndex(0),
            },
        };
        assert_eq!(
            DecisionEvidenceBodies::derive(&context, &basis, &request, &fold),
            Err(RefusalCode::ConflictingSemanticEffects),
            "a terminal refusal must use the refusal-evidence path, never a committing body set"
        );
    }

    #[test]
    fn refusal_evidence_is_a_distinct_canonical_basis_bound_body() {
        let (context, basis, request, _) = fixture();
        let first = RefusalEvidenceBodies::derive(
            &context,
            &basis,
            request.tx_id,
            RefusalCode::ExpectedOldRefMismatch,
        )
        .expect("typed refusal derives its witness");
        let second = RefusalEvidenceBodies::derive(
            &context,
            &basis,
            request.tx_id,
            RefusalCode::ExpectedOldRefMismatch,
        )
        .expect("same refusal derives the same witness");
        let different_code = RefusalEvidenceBodies::derive(
            &context,
            &basis,
            request.tx_id,
            RefusalCode::NonFastForwardRefused,
        )
        .expect("a distinct terminal code derives a distinct witness");
        let mut different_head_body = basis.body().clone();
        different_head_body.configuration_root = digest_of(8);
        let different_basis = PublicationBasis::new(
            fgit_types::RepositoryAuthorityHeadId::from_internal_object_id(
                body_id(&CryptoBodyIdentity, &different_head_body)
                    .expect("fixed authority head body identifies"),
            )
            .expect("authority-head identity has its pinned domain"),
            different_head_body,
        );
        let different_basis_witness = RefusalEvidenceBodies::derive(
            &context,
            &different_basis,
            request.tx_id,
            RefusalCode::ExpectedOldRefMismatch,
        )
        .expect("a distinct authenticated basis derives a witness");

        let frame = encode_body(first.refusal_evidence()).expect("refusal evidence frames");
        assert_eq!(
            decode_body::<RefusalEvidence>(&frame, fgit_codec::DecodeLimits::DEFAULT)
                .expect("refusal evidence frame decodes"),
            first.refusal_evidence().clone()
        );
        assert_eq!(first, second, "same refusal derivation is deterministic");
        assert_ne!(
            evidence_root(first.refusal_evidence()).expect("first refusal root"),
            evidence_root(different_code.refusal_evidence()).expect("different-code root"),
            "the supporting evidence commits the terminal refusal code"
        );
        assert_ne!(
            evidence_root(first.refusal_evidence()).expect("first refusal root"),
            evidence_root(different_basis_witness.refusal_evidence())
                .expect("different-basis root"),
            "the supporting evidence commits the exact authenticated basis"
        );
        assert_ne!(
            evidence_root(first.refusal_evidence()).expect("refusal root"),
            evidence_root(first.principal_snapshot()).expect("snapshot root"),
            "refusal evidence uses a domain distinct from its principal witness"
        );
    }
}
