// Uses the actual persisted checkpoint witness, filesystem and signing code.
import test from 'node:test';
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { readFile, readdir, unlink } from 'node:fs/promises';
import { initializeRepositoryBackupWitness, withRepositoryBackupWitness } from '../lib/repository-backup-witness.mjs';
import { jobFixture, DATA } from './repository-backup-job-fixture.mjs';

async function setup(t) {
  const f = await jobFixture(t), directory = join(f.root, 'witness');
  await initializeRepositoryBackupWitness(directory, f.trustKey, f.policy, { now: f.now });
  const own = (action, options = {}) => withRepositoryBackupWitness(directory, f.trustKey, f.policy,
    { now: f.now, ...options }, action);
  return { ...f, directory, own };
}

test('witness-bound job cannot resume without its originally selected witness', async t => {
  const f = await setup(t), job = await f.own(witness => f.seal({}, witness));
  assert.equal(job.witness_directory, f.directory);
  await assert.rejects(f.run(job.intent), { code: 'backup_job_witness_required' });
  const run = await f.own(witness => f.run(job.intent, {}, witness));
  assert.equal(run.state, 'complete'); assert.equal(run.result.highest_retained_generation_enforced, true);
  assert.equal(run.result.recovery_witness.highest_observed_generation, '9007199254740993');
});

test('retained newer checkpoint blocks an exact older job even when original source is still valid', async t => {
  const f = await setup(t), job = await f.own(witness => f.seal({}, witness));
  const newer = await f.sign('newer', DATA, '9007199254740994');
  await f.own(witness => readFile(newer.approval).then(bytes => witness.observe(bytes)));
  await unlink(newer.input); await unlink(newer.approval);
  await assert.rejects(f.own(witness => f.run(job.intent, {}, witness)), { code: 'backup_below_witness' });
  for (const path of f.destinations) assert.deepEqual(await readdir(path), []);
});

test('same-generation signed conflicts remain blocking across job retries', async t => {
  const f = await setup(t), job = await f.own(witness => f.seal({}, witness));
  const other = await f.sign('conflict', Buffer.alloc(DATA.length, 0x55));
  await f.own(witness => readFile(other.approval).then(bytes => witness.observe(bytes)));
  await assert.rejects(f.own(witness => f.run(job.intent, {}, witness)), { code: 'backup_witness_checkpoint_ambiguous' });
  const view = await f.own(witness => witness.snapshot()); assert.equal(view.conflicting_statements, true);
});

test('an expired job retains its signed generation before refusing, even on first witnessed run', async t => {
  const f = await setup(t), job = await f.seal();
  await assert.rejects(f.own(witness => f.run(job.intent, { now: f.now + 86401000 }, witness)), { code: 'backup_approval_expired' });
  const view = await f.own(witness => witness.snapshot()); assert.equal(view.highest_observed_generation, '9007199254740993');
});

test('a job above this attempts archive ceiling still retains signed higher evidence', async t => {
  const f = await setup(t), job = await f.seal();
  await assert.rejects(f.own(witness => f.run(job.intent, { maximumBytes: DATA.length - 1 }, witness)), { code: 'backup_selected_archive_limit' });
  assert.equal((await f.own(witness => witness.snapshot())).highest_observed_generation, '9007199254740993');
});

test('lease spans every publication and ordinary cancellation releases it for exact restart', async t => {
  const f = await setup(t), job = await f.own(witness => f.seal({}, witness)), stop = new AbortController(); let blocked = false;
  await assert.rejects(f.own(witness => f.run(job.intent, { signal: stop.signal, async onProgress(event) {
    if (event.phase === 'replica_complete' && event.completed_destinations === 1) {
      await assert.rejects(f.own(other => other.snapshot()), { code: 'backup_witness_locked' }); blocked = true; stop.abort();
    }
  } }, witness)), { code: 'backup_cancelled' });
  assert.equal(blocked, true); await unlink(f.source.input); await unlink(f.source.approval);
  const run = await f.own(witness => f.run(job.intent, {}, witness)); assert.equal(run.state, 'complete');
});

test('missing witness state is not regenerated by a job', async t => {
  const f = await setup(t), job = await f.own(witness => f.seal({}, witness));
  await unlink(join(f.directory, 'witness.json'));
  await assert.rejects(f.own(witness => f.run(job.intent, {}, witness)), { code: 'ENOENT' });
  assert.deepEqual(await readdir(f.directory), []);
});

test('a different empty witness cannot replace a bound one', async t => {
  const f = await setup(t), job = await f.own(witness => f.seal({}, witness)), other = join(f.root, 'other-witness');
  await initializeRepositoryBackupWitness(other, f.trustKey, f.policy, { now: f.now });
  await assert.rejects(withRepositoryBackupWitness(other, f.trustKey, f.policy, { now: f.now }, witness => f.run(job.intent, {}, witness)),
    { code: 'backup_job_witness_required' });
});
